void writeVerdicts(const VerdictMap& verdicts, std::ostream& out) {
    out << "{\n  \"verdicts\": [\n";
    bool first = true;
    for (const auto& [key, line] : verdicts) {
        auto tab = key.find('\t');
        auto instance = key.substr(0, tab);
        auto property = tab == std::string::npos ? std::string()
                                                 : key.substr(tab + 1);
        out << (first ? "" : ",\n") << "    {\"instance\": \""
            << escape(instance) << "\", \"property\": \"" << escape(property)
            << "\", \"status\": \"" << escape(line.status)
            << "\", \"detail\": \"" << escape(line.detail)
            // What the engine was asked. A verdict replayed onto a property
            // whose text has since changed would be an answer to a question
            // nobody asked; with this in the record, the product can tell.
            << "\", \"content\": \"" << escape(line.content)
            // ... and what it was allowed to stand on while answering.
            << "\", \"environment\": \"" << escape(line.environment)
            // WHERE THE COUNTEREXAMPLE IS. A path, and nothing about it is
            // fingerprinted: the trace is DERIVED EVIDENCE, regenerated by
            // whichever run decides the property, and not part of what the
            // verdict says. Fingerprinting it would retire a verdict because
            // a file it points at was rewritten byte-identically, which is a
            // fact about the filesystem and not about the question or the
            // environment.
            << "\", \"trace\": \"" << escape(line.trace)
            // WHAT IT STOOD ON. Additive, always written -- a table that
            // reads this record must be able to ask every row the question
            // and get an answer, and the empty string is the answer for a
            // row that has no verdict to qualify. Not fingerprinted and not
            // compared: it retires nothing (see ProofLine::premiseTier).
            << "\", \"premise_tier\": \"" << escape(line.premiseTier) << "\"";
        // THE TWO ESCALATION FIELDS, WRITTEN ONLY WHEN THEY SAY SOMETHING.
        //
        // Additive in the strict sense: a run that escalated nothing writes
        // the record it has always written, byte for byte, so the stability
        // sweep against an older binary compares files rather than schemas.
        // A reader that does not know the fields is unaffected; a reader that
        // does treats an absent field exactly as it treats an absent
        // `content' -- as "this record predates the question", which for the
        // engine is the same answer as "the in-process engine".
        if (!line.engine.empty())
            out << ", \"engine\": \"" << escape(line.engine) << "\"";
        if (!line.escalatedFrom.empty())
            out << ", \"escalated_from\": \"" << escape(line.escalatedFrom)
                << "\"";
        if (!line.route.empty())
            out << ", \"route\": \"" << escape(line.route) << "\"";
        if (!line.symEvalRecord.empty())
            out << ", \"symeval\": true, \"symeval_record\": \""
                << escape(line.symEvalRecord) << "\"";
        if (!line.evidenceOrigin.empty())
            out << ", \"evidence_origin\": \""
                << escape(line.evidenceOrigin) << "\"";
        if (!line.symEvalAntecedent.empty())
            out << ", \"symeval_antecedent\": \""
                << escape(line.symEvalAntecedent) << "\"";
        // Appended after every pre-existing key. Historical missing values
        // and null both mean this landing had no in-process attempt.
        out << ", \"seconds\": ";
        if (line.seconds)
            out << *line.seconds;
        else
            out << "null";
        out << ", \"peak_rss_kb\": ";
        if (line.peakRssKb)
            out << *line.peakRssKb;
        else
            out << "null";
        out << ", \"assumptions_in_force\": ";
        writeStringArray(out, line.assumptionsInForce);
        out << ", \"assumptions_dropped\": ";
        writeStringArray(out, line.assumptionsDropped);
        out << "}";
        first = false;
    }
    out << "\n  ]\n}\n";
}

VerdictMap readVerdicts(std::istream& in, const std::string& sourcePath) {
    try {
        const std::string text((std::istreambuf_iterator<char>(in)),
                               std::istreambuf_iterator<char>());
        if (in.bad()) throw std::runtime_error("could not read verdict JSON");
        const auto document = result_validation::parse(text);
        if (!document.is_object() || !to_json_object(document)["verdicts"].is_array())
            throw std::runtime_error("invalid verdict JSON document");

        // No partially validated map escapes if any row is malformed.
        VerdictMap verdicts;
        for (const auto& entry : to_json_array(to_json_object(document)["verdicts"])) {
            if (!entry.is_object()) throw std::runtime_error("invalid verdict JSON row");
            const auto& row = to_json_object(entry);
            const auto instance = verdictString(row, "instance", true);
            const auto property = verdictString(row, "property", true);
            if (instance.find('\t') != std::string::npos)
                throw std::runtime_error("ambiguous tab in verdict instance key");
            lowering::ProofLine line;
            line.status = verdictString(row, "status", true);
            line.detail = verdictString(row, "detail");
            line.content = verdictString(row, "content");
            line.environment = verdictString(row, "environment");
            line.trace = verdictString(row, "trace");
            line.premiseTier = verdictString(row, "premise_tier");
            line.engine = verdictString(row, "engine");
            line.escalatedFrom = verdictString(row, "escalated_from");
            line.route = verdictString(row, "route");
            line.symEvalRecord = verdictString(row, "symeval_record");
            line.evidenceOrigin = verdictString(row, "evidence_origin");
            line.symEvalAntecedent = verdictString(row, "symeval_antecedent");
            if (!row["symeval"].is_null() && !row["symeval"].is_boolean())
                throw std::runtime_error("invalid verdict symeval marker");
            line.seconds = verdictSeconds(row);
            line.peakRssKb = verdictRss(row);
            line.assumptionsInForce = verdictStrings(row, "assumptions_in_force");
            line.assumptionsDropped = verdictStrings(row, "assumptions_dropped");
            const auto key = lowering::proofKey(instance, property);
            if (!verdicts.emplace(key, std::move(line)).second)
                throw std::runtime_error("duplicate verdict landing");
        }
        return verdicts;
    } catch (const std::exception& error) {
        if (sourcePath.empty()) throw;
        throw std::runtime_error("cannot read verdict ledger " + sourcePath + ": " + error.what());
    }
}

