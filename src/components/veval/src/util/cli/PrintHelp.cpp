#include "ParseArguments.h"
#include <iostream>
namespace veval::cli {

void usage() {
    std::cout
        << "veval — property transport across a SystemVerilog hierarchy\n"
           "\n"
           "Usage: veval sigma --top MODULE [options] FILE...\n"
           "\n"
           "Commands:\n"
           "  check FILE.sby [TASK]  verify a task, publish local results and resume\n"
           "                   (separate options: veval check --help)\n"
           "  lower FILE.sby [TASK] --out DIR  generate reusable checks, without solving\n"
           "                   (run selected checks with consflow_check --help)\n"
           "  sigma            print the connection map of the top module\n"
           "  freex            rewrite a netlist's synthesis don't-cares into\n"
           "                   free values, one undriven wire each -- the\n"
           "                   model a PROVED verdict must come from\n"
           "  inspect-sva      inspect the shared SVA encoding (diagnostic)\n"
           "  transport        push each property down each instantiation edge\n"
           "  contracts        emit the environment contracts sigma already\n"
           "                   states -- tied-off inputs. Not broadcast intent\n"
           "                   and never counted with it\n"
           "  reach            which modules a specification at this boundary\n"
           "                   could ever touch, before any is written\n"
           "\n"
           "Options:\n"
           "  --top MODULE     top module (required)\n"
           "  --clock PORT     transport: sample on this one-bit input port in\n"
           "                   each property-bearing product; overrides naming\n"
           "                   inference. Missing/invalid ports are errors.\n"
           "  --assertion LABEL  transport: only this source assertion (exact label;\n"
           "                   repeatable); every assumption and reset contract\n"
           "                   is kept\n"
           "  --multiclock     transport: products are checked with every clock\n"
           "                   event; each samples on the port the source clock\n"
           "                   reaches by whole bindings, and ties the design's\n"
           "                   constant and shared-clock inputs in its own\n"
           "                   connections\n"
           "  --product-instance PATH  transport: export products only for this\n"
           "                   exact instance; keep the full transport log.\n"
           "  --json           emit JSON instead of text\n"
           "  --json-out FILE  transport: also write the JSON report to FILE, so\n"
           "                   one run serves both a reader and the manifest\n"
           "  -I PATH          Verilog include path (repeatable)\n"
           "  -D NAME[=VALUE]  preprocessor define (repeatable)\n"
           "  --verilog        parse as Verilog rather than SystemVerilog\n"
           "  -v N             frontend verbosity, 0 (silent) to 10\n"
           "  --property SUBSTR keep only properties whose name contains\n"
           "                   SUBSTR (repeatable); the default is all of\n"
           "                   them, including the design's own assertions\n"
           "  --out PATH       the tool's product. transport: a directory,\n"
           "                   one <module>_spec.sv (Tier-1 and the design's\n"
           "                   own constants) per module that received\n"
           "                   anything. freex: the\n"
           "                   rewritten netlist\n"
           "  --tier2-notes    transport: also write Tier2/<module>_notes.md\n"
           "                   explanations (off by default; counts unchanged)\n"
           "  --result-layout  transport: write the unified Result layout\n"
           "                   (products/, optional tier2/, by-verdict/, README.md and\n"
           "                   manifest.json) below --out\n"
           "  --config FILE    transport: the run's settings file (a TOML\n"
           "                   subset: environment_profile, placement,\n"
           "                   and an [engine] table parsed but not yet applied).\n"
           "                   The FILE WINS over the flags -- see src/util/cli/GenerationConfig.h\n"
           "                   -- and the merged values are written to\n"
           "                   <log>/effective_config.json\n"
           "  --placement single-path|split|root  transport:\n"
           "                   single-path (default) is\n"
           "                   one chain per property ending at\n"
           "                   the parent when two children share its signals or\n"
           "                   the child only reads them; split keeps every\n"
           "                   landing, assumptions by direction included.\n"
           "                   root binds the wrapper to its single whole DUT\n"
           "                   and preserves authored assertion/assumption roles.\n"
           "  --generation-profile PATH  transport: flushed diagnostic phase JSONL\n"
           "  -j N, -jN        lower/transport: accepted for compatibility, generation uses one thread\n"
           "  --generation-threads N     same as -j N\n"
           "  --log DIR        transport: write the machine-readable record\n"
           "                   to DIR -- transport.json and discharge.json: which\n"
           "                   instance owes each assumption the product\n"
           "                   grants, and what became of it. What\n"
           "                   experiments read\n"
           "  --log-format both|sqlite  transport: keep JSON and SQLite (default\n"
           "                   both), or omit the four duplicate transport,\n"
           "                   reach, graph and discharge JSON reports. Native\n"
           "                   lowering bundles use sqlite; legacy reports need both\n"
           "  --list PATH      freex: where to write the generated names\n"
           "  --boundary INST  reach: start from this instance rather than the\n"
           "                   top module\n"
           "  --to INST        reach: list the boundary signals that arrive at\n"
           "                   INST, which is what a property may be built of\n"
           "  --boundary-depth N  reach: try every instance down to depth N as\n"
           "                   a boundary, and report a greedy cover\n"
           "  --internal       reach: let the boundary be every signal declared\n"
           "                   in the module, not only its ports -- a decoded\n"
           "                   instruction bundle is an interface too\n"
           "  --min-signals N  reach: count a module covered only when N\n"
           "                   boundary signals arrive (default 3; two is the\n"
           "                   clock and the reset)\n"
           "\nThe built-in EBMC solver and its prove/evaluate options have been removed.\n"
           "Use lower to generate checks and check/consflow_check to run SymbiYosys.\n";
}


} // namespace veval::cli
