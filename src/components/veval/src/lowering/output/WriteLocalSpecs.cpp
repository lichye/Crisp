std::string display(const irep_idt& id) {
    return frontend::displayName(id2string(id));
}

// Only files with this marker may be removed during output cleanup.
const char kGeneratedMarker[] = "GENERATED by veval transport";

// Optional explanations live separately from compilable products.
const char kTier2Dir[] = "Tier2";

// The generated marker is confined to the first sixteen header lines.
bool generatedFile(const std::filesystem::path& path) {
    std::ifstream in(path);
    if (!in) return false;
    std::string line;
    for (int read = 0; read < 16 && std::getline(in, line); read++)
        if (line.find(kGeneratedMarker) != std::string::npos) return true;
    return false;
}

// Validate ownership before publishing or sweeping: root .sv files and every
// Tier2 entry must be generated. Other root subdirectories are refused.
void refuseUnlessOurs(const std::string& outDir) {
    const std::string advice =
        ". --out is regenerated whole and swept of the files an earlier run "
        "left, so it must be a directory this tool owns -- point it somewhere "
        "else, or move that file out";
    auto refuse = [&](const std::string& shown) {
        throw std::runtime_error(
            "refusing to write products into " + outDir + ": " + shown +
            " was not generated by veval (no `" + kGeneratedMarker +
            "' header)" + advice);
    };
    for (const auto& entry : std::filesystem::directory_iterator(outDir)) {
        if (entry.is_directory()) {
            if (entry.path().filename() != kTier2Dir)
                throw std::runtime_error(
                    "refusing to write products into " + outDir + ": " +
                    entry.path().filename().string() +
                    "/ is a subdirectory veval does not write -- the only one "
                    "it writes is `" + std::string(kTier2Dir) + "/'" + advice);
            for (const auto& note :
                 std::filesystem::directory_iterator(entry.path())) {
                if (note.is_regular_file() && generatedFile(note.path()))
                    continue;
                refuse(std::string(kTier2Dir) + "/" +
                       note.path().filename().string());
            }
            continue;
        }
        if (!entry.is_regular_file()) continue;
        if (entry.path().extension() != ".sv") continue;
        if (generatedFile(entry.path())) continue;
        refuse(entry.path().filename().string());
    }
}

// Map specialized module/instance names to filesystem-safe stems.
std::string sanitize(const std::string& name) {
    std::string out;
    out.reserve(name.size());
    for (char ch : name)
        out += (std::isalnum(static_cast<unsigned char>(ch)) || ch == '_')
                   ? ch
                   : '_';
    return out;
}

// Escaped Verilog identifiers require the trailing space.
std::string identifier(const std::string& name) {
    bool plain = !name.empty() && !std::isdigit(static_cast<unsigned char>(name[0]));
    for (char ch : name)
        plain = plain &&
                (std::isalnum(static_cast<unsigned char>(ch)) || ch == '_');
    return plain ? name : "\\" + name + " ";
}

std::string bareName(const symbol_exprt& port) {
    auto name = display(port.get_identifier());
    auto dot = name.rfind('.');
    return dot == std::string::npos ? name : name.substr(dot + 1);
}

struct Port {
    std::string name;
    bool isOutput;
    std::size_t width;
    bool isSigned = false;
    const InstanceEdge::ProductPortType* type = nullptr;
};

std::string portDeclaration(const Port& port) {
    std::ostringstream out;
    out << (port.isOutput ? "output " : "input ");
    if (port.type)
        return out.str() + port.type->declare(identifier(port.name));
    out << "logic";
    if (port.isSigned) out << " signed";
    if (port.width > 1) out << " [" << port.width - 1 << ":0]";
    out << " " << port.name;
    return out.str();
}

std::string clockPort(const InstanceEdge& edge) {
    for (const auto& binding : edge.bindings) {
        if (binding.isOutput) continue;
        auto base = bareName(binding.port);
        if (base == "clock" || base.compare(0, 3, "clk") == 0) return base;
    }
    return {};
}

// Use wrapper names for direct ports and u_dut references for internal objects.
exprt bare(exprt expr, const std::string& instanceDisplay,
           const namespacet& ns) {
    if (expr.id() == ID_symbol) {
        auto name = display(to_symbol_expr(expr).get_identifier());
        if (name.compare(0, instanceDisplay.size() + 1,
                         instanceDisplay + ".") == 0)
        {
            const auto relative = name.substr(instanceDisplay.size() + 1);
            const symbolt* symbol = nullptr;
            const bool port = !ns.lookup(to_symbol_expr(expr).get_identifier(), symbol)
                && (symbol->is_input || symbol->is_output)
                && relative.find('.') == std::string::npos;
            return symbol_exprt{port ? relative : "u_dut." + relative,
                                expr.type()};
        }
        return expr;
    }
    for (auto& op : expr.operands()) op = bare(std::move(op), instanceDisplay, ns);
    // Internal objects retain declared ranges; cast selects to a zero-based vector
    // to avoid applying their declared offset twice in the Verilog printer.
    if ((expr.id() == ID_extractbit || expr.id() == ID_extractbits) &&
        !expr.operands().empty()) {
        exprt* source = &expr.operands()[0];
        if (source->id() == ID_lshr && !source->operands().empty())
            source = &source->operands()[0];
        const auto& type = source->type();
        const auto offset = id2string(type.get(ID_C_offset));
        const exprt* root = source;
        while ((root->id() == ID_index || root->id() == ID_member) && !root->operands().empty())
            root = &root->operands()[0];
        if (root->id() == ID_symbol &&
            id2string(to_symbol_expr(*root).get_identifier()).compare(0, 6, "u_dut.") == 0 &&
            can_cast_type<bitvector_typet>(type) &&
            ((!offset.empty() && offset != "0") || type.get_bool(ID_C_increasing))) {
            const auto width = to_bitvector_type(type).get_width();
            *source = verilog_explicit_size_cast_exprt{
                from_integer(width, integer_typet{}), *source, type};
        }
    }
    return expr;
}

// Use a stable hash for persisted fingerprints; std::hash is not portable.
std::string fingerprint(const std::string& text) {
    std::uint64_t hash = 1469598103934665603ull;
    for (unsigned char ch : text) {
        hash ^= ch;
        hash *= 1099511628211ull;
    }
    std::ostringstream out;
    out << std::hex << std::setw(16) << std::setfill('0') << hash;
    return out.str();
}

