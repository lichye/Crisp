// Filter to this instance's declared inputs; edges can also contain descendant bindings.
std::vector<ConstantBinding> constantInputBindings(const InstanceEdge& edge,
                                                   const namespacet& ns) {
    std::vector<ConstantBinding> bindings;
    std::set<irep_idt> seen;
    const auto prefix = edge.instance + '.';

    for (const auto& binding : edge.bindings) {
        if (binding.isOutput)
            continue;

        const auto id = binding.port.get_identifier();
        const auto shown = display(id);
        if (shown.compare(0, prefix.size(), prefix) != 0 ||
            shown.find('.', prefix.size()) != std::string::npos)
            continue;
        if (!seen.insert(id).second) continue;

        const symbolt* symbol = nullptr;
        if (ns.lookup(id, symbol) || !symbol->is_input) continue;
        auto parts=constantBindingParts(binding);
        bindings.insert(bindings.end(), parts.begin(), parts.end());
    }
    return bindings;
}

std::string propertyFingerprint(const PropertyLanding& transport,
                                const namespacet& ns) {
    try {
        const auto expression = printedExpression(transport, ns);
        const auto text = propertyText(expression, &ns);
        if (!text) return {};
        return fingerprint(util::svaSentence(localDeclarationsText(expression, ns), *text));
    } catch (const frontend::FunctionPrintError&) {
        return {};
    }
}

std::string boundaryPropertyText(const PropertyLanding& transport,
                                 const namespacet& ns) {
    // Only direct routes carry the original boundary monitor.
    if (transport.routeDepth != 0) return {};
    if (transport.source.sourceProperty.is_nil()) return {};
    // Use real names, not the placeholders returned by a shape-only rendering.
    auto text = propertyText(transport.source.sourceProperty, &ns);
    return text ? *text : std::string();
}

ModuleSpecStats writeModuleSpecs(const std::vector<PropertyLanding>& transports,
                                 const std::map<irep_idt, irep_idt>& aliases,
                                 const namespacet& ns,
                                 const ModuleSpecOptions& options) {
    ModuleSpecStats stats;
    const auto sync = options.syncPerFile ? util::AtomicOutputSync::PerFile : util::AtomicOutputSync::Deferred;

    // Share prerequisite lookups across all products in this run.
    std::map<std::string, std::string> declarationCache;
    const auto rememberDeclaration = [&](const frontend::VerilogTypeDeclaration& type) {
        if (type.name.empty()) return;
        const auto key = type.scope == "$unit"
            ? "name:" + type.name : "package:" + type.scope;
        declarationCache[key] = type.declarationFile;
    };

    // Keep instance-specific environments separate even when instances share a module type.
    std::map<std::string, std::vector<const PropertyLanding*>> byInstance;
    std::map<std::string, std::set<std::string>> instancesOf;
    std::set<std::string> boundaryProperties;
    for (const auto& transport : transports) {
        byInstance[transport.instance].push_back(&transport);
        instancesOf[transport.module].insert(transport.instance);
        if (!transport.isResetContract)
            boundaryProperties.insert(transport.property);
    }

    if (!options.instanceOnly.empty() && !byInstance.count(options.instanceOnly))
        throw std::runtime_error("--product-instance has no transport instance: " + options.instanceOnly);

    const std::size_t stated = options.boundaryProperties != 0
                                   ? options.boundaryProperties
                                   : boundaryProperties.size();

    std::filesystem::create_directories(options.outDir);
    refuseUnlessOurs(options.outDir);
    const auto tier2Dir = options.tier2Dir.empty()
                              ? std::filesystem::path(options.outDir) / kTier2Dir
                              : std::filesystem::path(options.tier2Dir);
    const auto tier2Reference = options.tier2Reference.empty()
                                    ? std::string(kTier2Dir)
                                    : options.tier2Reference;
    const auto productReference = options.productReferenceFromTier2.empty()
                                      ? std::string("..")
                                      : options.productReferenceFromTier2;

    // Track the two output directories separately when removing stale generated files.
    std::set<std::string> writtenSpecs, writtenNotes;
    std::map<std::string, std::string> stemOwners;

    for (const auto& [instanceKey, rows] : byInstance) {
        if (!options.instanceOnly.empty() && instanceKey != options.instanceOnly) continue;
        const auto& module = rows.front()->module;
        bool shared = instancesOf.at(module).size() > 1;
        const auto entries = classifyProductEntries(rows);
        const auto& carried = entries.carried;
        // All rows in this group describe the same instance and parameter context.
        const auto& edge = *rows.front()->edge;
        auto contracts = designContracts(edge, ns);
        if (carried.empty() && entries.partial.empty() && entries.blocked.empty() &&
            entries.aggregated == 0 && contracts.empty())
            continue;

        const auto identity = shared ? module + "__" + instanceKey : module;
        auto stem = sanitize(identity);
        // Keep stems below NAME_MAX; the header retains the full identity.
        if (stem.size() > 200)
            stem = stem.substr(0, 180) + "__" + fingerprint(identity);
        const auto owner = stemOwners.emplace(stem, identity);
        if (!owner.second && owner.first->second != identity)
            throw std::runtime_error("generated product filename collision: " + stem);
        const auto wrapper = stem + "_spec";
        const auto notesName = stem + "_notes.md";
        const auto notesRef = tier2Reference + "/" + notesName;
        const auto specRef = productReference + "/" + wrapper + ".sv";
        const std::size_t tier2 = entries.partial.size() + entries.blocked.size();
        const auto notListed = entries.counted;

        // Counts are independent of whether explanation files are enabled.
        const bool hasTier2 = tier2 != 0 || entries.aggregated != 0;
        if (hasTier2) {
            stats.tier2Partial += entries.partial.size();
            stats.tier2Blocked += entries.blocked.size();
            stats.tier2Aggregated += entries.aggregated;
            stats.tier2Counted += notListed;
        }
        if (options.tier2Notes && hasTier2) {
            std::filesystem::create_directories(tier2Dir);
            auto notesPath = tier2Dir / notesName;
            util::writeAtomic(notesPath.string(), [&](std::ostream& notes) {

                notes << "# " << module << " -- transport notes\n"
                      << "\n"
                      << "    module:   " << module << "\n"
                      << "    instance: " << edge.instance << "\n"
                      << "    boundary: " << options.boundary;
                if (!options.boundarySpecPath.empty())
                    notes << " (" << options.boundarySpecPath << ")";
                notes << "\n"
                      << "\n"
                      << "GENERATED by veval transport. Do not edit; regenerate.\n"
                      << "\n"
                      << "Ledger: the boundary states " << properties(stated)
                      << ". "
                      << (!carried.empty()
                              ? arrive(carried.size()) + " here, written out in `" +
                                    specRef + "'"
                          : contracts.empty()
                              ? std::string("None arrives at this module, so "
                                            "there is no `") +
                                    specRef + "'"
                              : std::string("None arrives at this module; `") +
                                    specRef +
                                    "' holds the design's own constants and "
                                    "nothing carried")
                      << "; "
                      << (tier2 == 0 ? std::string("nothing is")
                                     : std::to_string(tier2) +
                                           (tier2 == 1 ? " is" : " are"))
                      << " written out below; " << notListed
                      << " more did not carry and "
                      << (notListed == 1 ? "is" : "are")
                      << " counted by class below, not written out.\n"
                      << "\n"
                      << "NOTHING IN THIS FILE IS ASSERTED OR ASSUMED. Each entry\n"
                         "says what stopped the property here and where to read it\n"
                         "in full: the boundary specification remains the only\n"
                         "statement of it.\n";

                for (const auto* row : entries.partial) {
                    writePartialNote(notes, options, *row);
                }
                for (const auto* row : entries.blocked) {
                    writeBlockedNote(notes, options, *row);
                }
                writeAggregateBreakdown(notes, entries.byClass, notListed);
            }, sync);
            writtenNotes.insert(notesName);
            stats.notes++;
        }

        if (!edge.productPortError.empty() || (carried.empty() && contracts.empty())) continue;

        const auto ports = declaredPorts(edge, ns);
        // Constant-only products need no design clock; use a wrapper clock when absent.
        auto clock = productClockPort(edge, carried.empty() ? "" : options.clockPort);
        if (!carried.empty() && !options.clockPort.empty()) {
            const auto port = std::find_if(ports.begin(), ports.end(),
                [&](const Port& p) { return p.name == clock; });
            if (port == ports.end() || port->isOutput || port->width != 1)
                throw std::runtime_error("--clock " + clock + ": expected a one-bit input port at " + edge.instance);
        }
        std::string clockBasis;
        SampledClock sampled;
        std::map<std::string, std::string> tied;
        // Clock aliases and constant ties are connected directly for clock-event products.
        // Sampled assumptions alone would not constrain values between events.
        if (options.multiclock && !carried.empty()) {
            sampled = sampledClock(edge, carried, aliases, options);
            const bool connected = std::find(sampled.ports.begin(), sampled.ports.end(), clock) != sampled.ports.end();
            if (connected) clockBasis = "whole-binding";
            else if (options.clockPort.empty() && !sampled.ports.empty()) { clock = sampled.ports.front(); clockBasis = "whole-binding"; }
            else clockBasis = sampled.why.empty() ? "unconnected" : sampled.why;
            if (clockBasis == "whole-binding")
                for (const auto& port : sampled.ports) if (port != clock) tied[port] = clock;
        }
        if (options.multiclock)
            for (const auto& contract : contracts) tied[contract.port] = contract.value;
        bool virtualClock = clock.empty();
        if (virtualClock) clock = "clk";

        auto path = std::filesystem::path(options.outDir) / (wrapper + ".sv");
        // Build the body first, then insert prerequisites derived from its actual text.
        std::ostringstream out;

        out << "// " << wrapper << ".sv -- GENERATED by veval transport."
            << " Do not edit; regenerate.\n"
            << "//\n"
            << "// module:   " << module << "\n"
            << "// instance: " << edge.instance << "\n"
            << "// boundary: " << options.boundary;
        if (!options.boundarySpecPath.empty())
            out << " (" << options.boundarySpecPath << ")";
        // Reference only explanation files that will actually exist.
        const bool notesFile = options.tier2Notes && hasTier2;
        out << "\n"
            << "// depth:    " << rows.front()->depth
            << " below the boundary\n"
            << "// arrived:  " << entries.whole << " whole, " << entries.inPart
            << " in part; " << entries.stopped << " stopped here, " << entries.unrelated
            << " unrelated\n";
        // Keep invocation details in the log so path-only changes do not alter products.
        if (!options.command.empty())
            out << "// command:  recorded verbatim in the run's "
                   "effective_config.json\n";
        out << "//\n"
            << "// ledger: boundary states " << properties(stated) << "; "
            << arrive(carried.size()) << " here; the rest: "
            << (notesFile ? "see " + notesRef
                         : hasTier2 ? "Tier-2 details omitted; enable --tier2-notes"
                                    : "none traced") << "\n"
            << "//\n"
            << "// Tier-1 entries: stated at the boundary and carried here\n"
               "// whole, round-trip checked. Proving one of them of this "
               "module alone\n"
               "// proves the boundary property on this edge. Each carries a\n"
               "// `proof:' line: what an engine said, or `unknown' when none "
               "has\n"
               "// been asked.\n"
               "// Tier-2 entries are NOT in this file. Nothing is asserted or\n"
               "// assumed about them";
        out << (!options.tier2Notes && hasTier2
                    ? "; details omitted (enable --tier2-notes).\n"
                : tier2 != 0
                    ? "; each is one pointer line in " + notesRef + ".\n"
                : notesFile
                    ? ", and this module has none written out: what did not\n"
                      "// carry here has no signal relation to it, and " +
                          notesRef + " counts it.\n"
                    : ", and this module has none.\n");
        if (virtualClock)
            out << "//\n"
                << "// The module has no clock port; `clk' below is the "
                   "wrapper's own\n"
                << "// sampling clock, the usual convention for a "
                   "combinational DUT.\n";
        if (referencesChildInstance(carried, edge.instance))
            out << "//\n"
                << "// One or more entries below name a signal INSIDE a "
                   "sub-instance of this\n"
                << "// module. That is deliberate and it is not a leaked "
                   "name: the signal\n"
                << "// belongs to a module further down, this instance is "
                   "the deepest one\n"
                << "// where the boundary's sentence still holds whole, and "
                   "the sentence is\n"
                << "// written in the names this module can see. It is a "
                   "step on the\n"
                << "// ownership path, not its end.\n";
        // Insert prerequisites before observations, after the main header.
        const auto headerEnd = static_cast<std::size_t>(out.tellp());
        std::map<std::string, std::string> observed;
        for (const auto* row : carried)
            observations(row->monitor.sourceProperty, edge, ns, observed);
        for (const auto& [id, record] : observed)
            out << "// observation: " << record << "\n";
        if (!clockBasis.empty()) {
            out << "// sampling: {\"schema\":\"veval-sampling/1\",\"source\":" << std::quoted(sampled.source)
                << ",\"port\":" << std::quoted(virtualClock ? std::string() : clock)
                << ",\"basis\":" << std::quoted(clockBasis) << ",\"tied\":{";
            bool firstTie = true;
            for (const auto& [port, value] : tied) {
                out << (firstTie ? "" : ",") << std::quoted(port) << ":" << std::quoted(value);
                firstTie = false;
            }
            out << "}}\n";
        }
        out << "\n" << "module " << wrapper << "(\n";

        bool first = true;
        if (virtualClock) {
            out << "    input logic clk";
            first = false;
        }
        for (const auto& port : ports) {
            if (tied.count(port.name)) continue;
            out << (first ? "" : ",\n") << "    " << portDeclaration(port);
            first = false;
        }
        out << "\n);\n\n";
        // A tied input is a local wire, not a free wrapper input.
        for (const auto& port : ports) {
            const auto tie = tied.find(port.name);
            if (tie == tied.end()) continue;
            if (port.type) {
                out << "  wire " << port.type->prefix << " " << identifier(port.name) << port.type->suffix;
            } else {
                out << "  wire" << (port.isSigned ? " signed" : "");
                if (port.width > 1) out << " [" << port.width - 1 << ":0]";
                out << " " << port.name;
            }
            out << " = " << tie->second << ";\n";
        }
        if (!tied.empty()) out << "\n";
        // Retain instance parameter values rather than elaborating module defaults.
        out << "  " << identifier(module);
        if (!edge.parameters.empty()) {
            out << " #(";
            bool firstParameter = true;
            for (const auto& [parameter, value] : edge.parameters) {
                out << (firstParameter ? "" : ", ") << "." << parameter << "(" << value << ")";
                firstParameter = false;
            }
            out << ")";
        }
        out << " u_dut(\n";
        first = true;
        for (const auto& port : ports) {
            const auto tie = tied.find(port.name);
            out << (first ? "" : ",\n") << "      ." << port.name << "("
                << (tie == tied.end() ? port.name : tie->second) << ")";
            first = false;
        }
        out << "\n  );\n";

        std::set<std::string> usedLabels;

        if (!options.environmentProfile.isFull())
            out << "\n  // Runtime environment profile: "
                << options.environmentProfile.name()
                << ". Transported assumptions omitted by this profile are "
                   "not emitted.\n";

        if (!contracts.empty()) {
            out << "\n  // ------------------------------------------------"
                << "---------------------\n"
                << "  // The design's own constants.\n"
                << "  // The design itself ties this input to a constant; "
                   "stated so the\n"
                << "  // module can be verified alone. Not carried intent.\n"
                << "  // ------------------------------------------------"
                << "---------------------\n";
        }
        for (std::size_t i = 0; i < contracts.size(); i++) {
            const auto label = "sigma_tie_" + std::to_string(i);
            usedLabels.insert(label);
            std::ostringstream raw;
            raw << json_irept(false).convert_from_irep(contracts[i].relation);
            auto relation = raw.str();
            relation.erase(std::remove(relation.begin(), relation.end(), '\n'), relation.end());
            out << "\n  // design-binding: {\"schema\":\"consflow-design-binding/1\","
                << "\"instance\":" << std::quoted(edge.instance)
                << ",\"module\":" << std::quoted(module)
                << ",\"port\":" << std::quoted(contracts[i].port)
                << ",\"relation\":" << relation << "}\n"
                << "  " << label << ": assume property (@(posedge " << clock
                << ")\n      " << contracts[i].subject << " == "
                << contracts[i].value << ");\n";
            stats.designStated++;
        }

        // Initial-state contracts are metadata here; an always-assume would change their meaning.
        auto environmentLines = options.environmentShown.find(edge.instance);
        if (environmentLines != options.environmentShown.end() &&
            !environmentLines->second.empty()) {
            out << "\n  // ------------------------------------------------"
                << "---------------------\n"
                << "  // The environment the check is given, derived from "
                   "the design\n"
                << "  // itself. Not carried intent, and nothing here is "
                   "asserted or\n"
                << "  // assumed of this module.\n"
                << "  // ------------------------------------------------"
                << "---------------------\n";
            for (const auto& line : environmentLines->second)
                out << "  // premise: " << line << "\n";
        }

        if (!contracts.empty() && !carried.empty()) {
            out << "\n  // ------------------------------------------------"
                << "---------------------\n"
                << "  // Tier-1: carried from the boundary.\n"
                << "  // ------------------------------------------------"
                << "---------------------\n";
        }

        // Emit assumptions first so each obligation names only previously emitted premises.
        std::vector<AssumptionCopy> copies;
        for (const auto* row : carried) {
            auto additional = copyPortAssumptions(*row);
            std::move(additional.begin(), additional.end(), std::back_inserter(copies));
        }
        auto ordered = carried;
        for (const auto& copy : copies) ordered.push_back(&copy.landing);
        std::stable_partition(ordered.begin(), ordered.end(), [](const PropertyLanding* row) {
            return row->isAssumptionHere || row->monitor.isAssumption;
        });
        // Include only labels actually emitted after environment-profile filtering.
        std::vector<std::string> emittedAssumptions;
        bool openedAssumptions = false, openedProperties = false;
        std::map<std::string, std::string> functionDefinitions;

        for (const auto* row : ordered) {
            auto label = lastComponent(row->property);
            while (!usedLabels.insert(label).second) label += "_";
            const auto& monitor = row->monitor;
            bool assume = row->isAssumptionHere || monitor.isAssumption;

            if (assume && !openedAssumptions) {
                openedAssumptions = true;
                out << "\n  // ---- assumptions ----------------------------"
                       "-----------------------\n"
                    << "  // Carried here from the boundary. This module may "
                       "rely on them;\n"
                    << "  // each is discharged where the signals it names "
                       "are driven.\n";
            }
            if (!assume && !openedProperties) {
                openedProperties = true;
                out << "\n  // ---- properties -----------------------------"
                       "-----------------------\n"
                    << "  // Tier-1: what this module is asked to establish. "
                       "Proving one of\n"
                    << "  // them of this module alone proves the boundary "
                       "property on this edge.\n";
            }

            if (usableAsAssumption(*row) &&
                !options.environmentProfile.usesAssumption(row->instance,
                                                            row->property)) {
                out << "\n  // omitted environment assumption from: "
                    << row->property << "\n";
                for (const auto& hop : row->flowEdges)
                    if (hop.kind == "symeval" &&
                        hop.record.compare(0, 6, "field:") == 0)
                        stats.fieldOmissions.push_back({hop.record, row->instance,
                            row->property, row->evidenceOrigin, path.string(),
                            options.environmentProfile.name()});
                continue;
            }

            const auto expression = printedExpression(*row, ns);
            const auto functions = frontend::prepareFunctionPrint(expression, ns);
            for (const auto& type : functions.prerequisites)
                rememberDeclaration(type);
            for (const auto& [name, definition] : functions.definitions) {
                const auto [found, inserted] = functionDefinitions.emplace(name, definition);
                if (inserted) out << '\n' << definition;
                else if (found->second != definition)
                    throw std::runtime_error("pure function name collision");
            }
            const auto localDeclarations = localDeclarationsText(expression, ns);
            const auto text = propertyText(expression, &ns);
            const auto localDefinition = "__cf_rule_" + label;
            if (!localDeclarations.empty()) {
                if (!text || assume) throw std::runtime_error("unsupported local-variable property: " + row->property);
                out << "\n  property " << localDefinition << ";\n    " << localDeclarations
                    << "\n    " << *text << ";\n  endproperty\n";
            }
            out << "\n  // Tier-1 -- carried whole, round-trip checked; route "
                   "depth "
                << row->routeDepth << "\n"
                << "  // from: " << row->property << "\n";
            if (row->abortDropped)
                out << "  // abort-dropped: stronger assertion body; target implies source.\n"
                    << "  // Round-trip checked against the source body without abort.\n"
                    << "  // Local counterexamples require source-context replay.\n";
            if (std::any_of(row->flowEdges.begin(), row->flowEdges.end(),
                           [](const auto& edge) { return edge.kind == "combinational-definition"; }))
                out << "  // Same-cycle ancestor definitions expanded before port substitution.\n";
            if (!row->evidenceOrigin.empty() &&
                std::any_of(row->flowEdges.begin(), row->flowEdges.end(),
                            [](const PropertyLanding::FlowEdge& edge) {
                                return edge.kind == "symeval" &&
                                       edge.record.compare(0, 6, "field:") == 0;
                            }))
                out << "  // original-source-entry: " << row->evidenceOrigin << "\n";
            writeRouteComment(out, *row);
            if (assume) {
                out << "  // arrival: "
                    << (row->result == LoweringCoverage::Full ? "full" : "partial");
                if (row->result != LoweringCoverage::Full) {
                    out << " (did not carry:";
                    for (const auto& dropped : row->dropped())
                        out << " " << dropped.signal << " ["
                            << dropped.reason << "]";
                    out << ")";
                }
                out << "\n";
            } else if (!emittedAssumptions.empty()) {
                out << "  // premises:";
                for (const auto& name : emittedAssumptions)
                    out << " " << name;
                out << "\n";
            }
            if (row->isAssumptionHere && !monitor.isAssumption)
                out << "  // assume, not assert: every signal arrives through "
                       "an input, so this\n"
                    << "  // is the environment the boundary guarantees, not "
                       "an obligation.\n";
            auto environmentAt =
                options.environmentFingerprint.find(row->instance);
            writeProofComment(
                out,
                proofBody(options, *row, assume,
                          text ? fingerprint(util::svaSentence(localDeclarations,*text)) : std::string(),
                          environmentAt == options.environmentFingerprint.end()
                              ? std::string()
                              : environmentAt->second),
                assume && options.discharge != nullptr);
            if (!text)
                throw std::runtime_error(
                    "no SystemVerilog spelling for " + row->property +
                    " at " + row->instance + ", yet it was sorted Tier-1");
            out << "  " << label << ": " << (assume ? "assume" : "assert")
                << " property (@(posedge " << clock << ")\n      " << (localDeclarations.empty() ? *text : localDefinition)
                << ");\n";
            if (assume) emittedAssumptions.push_back(label);
            stats.tier1++;

            // Warn direct external-EBMC users when that engine ignores the SVA assumption shape.
            if (assume && veval::sva::engineDropsAsAssumption(
                              monitor.sourceProperty))
                std::cerr
                    << "WARNING: " << wrapper << ".sv writes `" << label
                    << "' as an assumption whose SVA shape the vendored ebmc "
                       "DROPS: k-induction reports it UNSUPPORTED and proves "
                       "without it, the BDD engine ignores it silently. "
                       "veval's own verdict on this file did NOT go that "
                       "route -- it spliced the assumption in as an automaton "
                       "-- so a direct `ebmc " << wrapper
                    << ".sv' run can disagree with the `proof:' line above, "
                       "and where it refutes it may be refuting without the "
                       "premise. From " << row->property << ".\n";
        }

        out << "\nendmodule\n";

        // Scan only the body; header diagnostics can contain unrelated scope-qualified names.
        const auto text = out.str();
        for (const auto& [port, type] : edge.productPortTypes)
            rememberDeclaration(type);
        const auto block = prerequisiteBlock(
            prerequisites(text.substr(headerEnd), options, declarationCache), wrapper);
        util::writeAtomic(path.string(), [&](std::ostream& file) {
            file << text.substr(0, headerEnd) << block << text.substr(headerEnd);
        }, sync);
        if (!block.empty()) stats.prerequisite++;
        writtenSpecs.insert(wrapper + ".sv");
        stats.specFiles.push_back(path.string());
        stats.files++;
    }

    // Remove only marked generated files with owned suffixes, including old-layout notes.
    auto sweep = [&](const std::filesystem::path& dir,
                     const std::string& owned,
                     const std::set<std::string>& written) {
        if (!std::filesystem::is_directory(dir)) return;
        for (const auto& entry : std::filesystem::directory_iterator(dir)) {
            if (!entry.is_regular_file()) continue;
            const auto name = entry.path().filename().string();
            auto ends = [&name](const std::string& suffix) {
                return name.size() > suffix.size() &&
                       name.compare(name.size() - suffix.size(), suffix.size(),
                                    suffix) == 0;
            };
            if (!ends("_spec.sv") && !ends("_notes.md")) continue;
            if (ends(owned) && written.count(name) != 0) continue;
            if (!generatedFile(entry.path())) continue;
            std::filesystem::remove(entry.path());
            stats.stale++;
        }
    };
    sweep(options.outDir, "_spec.sv", writtenSpecs);
    sweep(tier2Dir, "_notes.md", writtenNotes);

    std::vector<std::string> outputDirectories{options.outDir};
    if (std::filesystem::is_directory(tier2Dir))
        outputDirectories.push_back(tier2Dir.string());
    util::syncAtomicOutputDirectories(outputDirectories, sync);

    return stats;
}

