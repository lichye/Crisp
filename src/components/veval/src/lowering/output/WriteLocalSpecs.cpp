// A common source event net must reach through whole bindings; gated clocks are distinct.
struct SampledClock {
    std::string source;              // the boundary net, "" when unknown or mixed
    std::string why;                 // when `ports' is empty
    std::vector<std::string> ports;  // one-bit inputs carrying it, binding order
};
SampledClock sampledClock(const InstanceEdge& edge, const std::vector<const PropertyLanding*>& carried,
                          const std::map<irep_idt, irep_idt>& aliases, const ModuleSpecOptions& options) {
    SampledClock result;
    std::set<std::string> nets;
    for (const auto* row : carried) {
        const auto found = options.samplingClocks.find(row->property);
        if (found == options.samplingClocks.end()) {
            result.why = "unknown"; return result;
        }
        nets.insert(found->second);
    }
    if (nets.size() != 1) { result.why = "mixed"; return result; }
    result.source = *nets.begin();
    const auto representative = [&](const irep_idt& id) {
        const auto found = aliases.find(id);
        return found == aliases.end() ? id : found->second;
    };
    const auto source = representative("Verilog::$root." + result.source);
    std::set<std::string> seen;
    for (const auto& binding : edge.bindings) {
        if (binding.isOutput || binding.kind != BindingKind::Whole) continue;
        const auto name = bareName(binding.port);
        const auto& type = binding.port.type();
        const bool oneBit = type.id() == ID_bool ||
            (type.id() == ID_unsignedbv && to_unsignedbv_type(type).get_width() == 1);
        if (!edge.ports.count(name) || !oneBit || seen.count(name)) continue;
        if (representative(binding.port.get_identifier()) == source && seen.insert(name).second)
            result.ports.push_back(name);
    }
    if (result.ports.empty()) result.why = "unconnected";
    return result;
}
