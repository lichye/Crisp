J projectEnvironmentInputs(Database &db, const std::string &root,
                           const J &queries, const J &inputs, const fs::path &dir) {
    veval::profile::Phase phase("environment.project");
    std::map<std::string, Instance> hierarchy;
    for (const auto &row : db.rows("SELECT instance,module,parent FROM instances"))
        hierarchy.emplace(text(row["instance"]), Instance{text(row["module"]), text(row["parent"])});
    std::set<std::string> needed, landings;
    for (const auto &q : items(queries)) {
        const auto landing = text(q["instance"]);
        if (landing == root || !landings.insert(landing).second) continue;
        if (!below(landing, root) || !hierarchy.count(landing)) return inputs;
        // A sibling such as u$other sorts before u.child. Start at the dotted
        // prefix; the ancestor walk below adds the landing itself.
        for (auto it = hierarchy.lower_bound(landing + "."); it != hierarchy.end() && below(it->first, landing); ++it)
            needed.insert(it->second.module);
        for (auto path = landing; !path.empty();) {
            const auto it = hierarchy.find(path);
            if (it == hierarchy.end()) return inputs;
            needed.insert(it->second.module);
            if (path == root) break;
            path = it->second.parent;
        }
    }
    if (needed.empty()) return inputs;
    std::set<std::string> boundary;
    for (const auto &[path, instance] : hierarchy) {
        const auto parent = hierarchy.find(instance.parent);
        if (parent != hierarchy.end() && needed.count(parent->second.module) && !needed.count(instance.module))
            boundary.insert(instance.module);
    }
    std::vector<Source> sources;
    std::set<std::string> found;
    for (const auto &input : items(inputs)) {
        if (text(input["role"]) != "design") continue;
        Source source{fs::path(text(input["path"])), {}, false};
        source.indexed = indexNetlist(source.path, source.modules);
        if (source.indexed)
            for (const auto &[name, range] : source.modules) {
                if (!found.insert(name).second) return inputs;
            }
        sources.push_back(std::move(source));
    }
    // A parameter-specialized module not present verbatim in the source needs
    // normal elaboration. Never infer its ports from another specialization.
    for (const auto &name : needed) if (!found.count(name)) return inputs;
    for (const auto &name : boundary) if (!found.count(name)) return inputs;
    if (found.size() <= needed.size() + boundary.size()) return inputs;
    J projected = list();
    std::size_t i = 0;
    for (const auto &source : sources) {
        if (!source.indexed) {
            append(projected, object({{"path", str(source.path.string())}, {"role", str("design")}}));
            continue;
        }
        for (const auto library : {false, true}) {
            const auto &selection = library ? boundary : needed;
            bool any = false;
            for (const auto &[name, range] : source.modules) any |= selection.count(name) != 0;
            if (!any) continue;
            const auto path = dir / ("design-" + std::to_string(i++) + (library ? "-ports.v" : ".v"));
            copyModules(source, selection, path);
            append(projected, object({{"path", str(path.string())}, {"role", str("design")}, {"ports_only", boolean(library)}}));
        }
    }
    veval::profile::count("environment.full-modules", needed.size());
    veval::profile::count("environment.boundary-modules", boundary.size());
    veval::profile::count("environment.omitted-modules", found.size() - needed.size() - boundary.size());
    return projected;
}
