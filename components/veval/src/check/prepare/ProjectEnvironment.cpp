using View = std::string_view;
struct Range { std::uint64_t begin, end; };
using Index = std::map<std::string, Range>;

View trim(View s) {
    const auto first = s.find_first_not_of(" \r\n\t");
    return first == s.npos ? View{} : s.substr(first, s.find_last_not_of(" \r\n\t") - first + 1);
}
View word(View &s) {
    s = trim(s);
    const auto end = s.find_first_of(s.empty() || s.front() != '\\' ? " \t\r\n(;#" : " \t\r\n");
    const auto out = s.substr(0, end);
    s.remove_prefix(out.size());
    return out;
}
std::string identifier(View s) {
    if (!s.empty() && s.front() == '\\') s.remove_prefix(1);
    return std::string(s);
}

// This shortcut accepts only standalone, elaborated Yosys netlists. Packages,
// macros, parameterized source and other layouts keep the general frontend.
bool indexNetlist(const fs::path &path, Index &modules) {
    std::ifstream in(path, std::ios::binary);
    std::string line, current;
    std::uint64_t offset = 0, prefix = 0, start = 0;
    bool block = false, generated = false;
    while (std::getline(in, line)) {
        const auto begin = offset;
        offset += line.size() + (in.eof() ? 0 : 1);
        if (!begin) generated = line.rfind("/* Generated by Yosys ", 0) == 0;
        if (!generated || line.find('`') != line.npos) return false;
        View code = trim(line);
        // The generated layout starts modules and endings on their own lines;
        // long port lists may continue on following lines.
        // Block comments may contain those words and must not become headers.
        if (block) {
            const auto end = code.find("*/");
            if (end == code.npos) continue;
            code = trim(code.substr(end + 2)); block = false;
        }
        while (code.substr(0, 2) == "/*") {
            const auto end = code.find("*/", 2);
            if (end == code.npos) { block = true; break; }
            code = trim(code.substr(end + 2));
        }
        if (block || code.empty() || code.substr(0, 2) == "//") continue;
        auto rest = code;
        const auto token = word(rest);
        if (token == "module") {
            if (!current.empty()) return false;
            current = identifier(word(rest));
            rest = trim(rest);
            if (current.empty() || rest.empty() || rest.front() != '(' ||
                rest.find("endmodule") != rest.npos) return false;
            start = prefix;
        } else if (token == "endmodule") {
            if (current.empty() || !trim(rest).empty()) return false;
            if (!modules.emplace(current, Range{start, offset}).second) return false;
            current.clear(); prefix = offset;
        } else if (current.empty() && code.substr(0, 2) != "(*") return false;
    }
    return in.eof() && !block && current.empty() && !modules.empty();
}

bool below(const std::string &path, const std::string &ancestor) {
    return path == ancestor || (path.size() > ancestor.size() &&
        path.compare(0, ancestor.size(), ancestor) == 0 && path[ancestor.size()] == '.');
}
struct Instance { std::string module, parent; };
struct Source { fs::path path; Index modules; bool indexed; };

void copyModules(const Source &source, const std::set<std::string> &selected,
                 const fs::path &output) {
    std::vector<Range> ranges;
    for (const auto &[name, range] : source.modules)
        if (selected.count(name)) ranges.push_back(range);
    std::sort(ranges.begin(), ranges.end(), [](auto a, auto b) { return a.begin < b.begin; });
    std::ifstream in(source.path, std::ios::binary);
    veval::util::writeAtomic(output.string(), [&](std::ostream &out) {
        std::array<char, 65536> buffer;
        for (const auto &range : ranges) {
            in.clear(); in.seekg(range.begin);
            for (auto left = range.end - range.begin; left;) {
                const auto n = std::min<std::uint64_t>(left, buffer.size());
                in.read(buffer.data(), n);
                if (in.gcount() != std::streamsize(n)) throw std::runtime_error("netlist changed while projecting environment");
                out.write(buffer.data(), n); left -= n;
            }
            out.put('\n');
        }
    });
}
